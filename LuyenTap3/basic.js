const tinhTong = (a, b) => a + b;
const tinhBinhPhuong = (n) => n * n;
const lonHon10 = (n) => n > 10;

console.log("Tổng 3 + 7 =", tinhTong(3, 7));
console.log("Tổng 15 + 20 =", tinhTong(15, 20));
console.log("Bình phương 5 =", tinhBinhPhuong(5));
console.log("Bình phương 9 =", tinhBinhPhuong(9));
console.log("12 lớn hơn 10?", lonHon10(12));
console.log("7 lớn hơn 10?", lonHon10(7));
